import { useEffect, useState, type ReactNode } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Loader2, Pencil, Plus, Trash2 } from "lucide-react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { supabase } from "@/lib/supabase";
import { SITE_DATA_KEY } from "@/lib/siteData";
import FieldInput from "@/components/admin/FieldInput";
import { checkForm, emptyForm, formToRow, rowToForm, type Field, type FormValues, type Row } from "@/lib/admin/fields";

export type ResourceConfig = {
  table: string;
  title: string;
  description?: string;
  /** Primary key column; "identity" keys are generated by the database. */
  pk: string;
  pkMode: "identity" | "text";
  order: { column: string; ascending?: boolean }[];
  fields: Field[];
  /** Values for a new row. */
  defaults?: Row;
  rowTitle: (row: Row) => string;
  rowSubtitle?: (row: Row) => ReactNode;
  rowImage?: (row: Row) => string | undefined;
  /** Extra buttons on each row (e.g. "copy link"). */
  rowActions?: (row: Row) => ReactNode;
  /** Changes here show up on the public site. */
  affectsSite?: boolean;
  /** Plain-language name of one item, for buttons: "paket", "FAQ". */
  itemName: string;
};

/** Friendly message for common database errors. */
export function dbErrorMessage(e: unknown): string {
  const msg = e && typeof e === "object" && "message" in e ? String((e as { message: unknown }).message) : String(e);
  const code = e && typeof e === "object" && "code" in e ? String((e as { code: unknown }).code) : "";
  if (code === "23505") return "Kode/ID itu sudah dipakai. Pakai yang lain.";
  if (code === "23514") return "Ada isian yang tidak memenuhi aturan (cek format kode, angka, atau link).";
  if (code === "42501" || /row-level security/i.test(msg)) return "Akun ini tidak punya izin admin untuk perubahan ini.";
  return msg || "Terjadi kesalahan.";
}

/**
 * List + add/edit/delete for one table, driven by a field list. Also used for embedded editors
 * (`prefill` opens the form with values, e.g. a member created from a booking).
 */
const ResourceEditor = ({ config, prefill, onPrefillUsed }: { config: ResourceConfig; prefill?: Row | null; onPrefillUsed?: () => void }) => {
  const qc = useQueryClient();
  const key = ["admin", config.table];
  const [editing, setEditing] = useState<{ row: Row | null; values: FormValues } | null>(null);
  const [errors, setErrors] = useState<Record<string, string>>({});

  const { data: rows = [], isLoading, error } = useQuery({
    queryKey: key,
    queryFn: async () => {
      let q = supabase!.from(config.table).select("*");
      for (const o of config.order) q = q.order(o.column, { ascending: o.ascending ?? true });
      const { data, error } = await q.limit(500);
      if (error) throw error;
      return (data ?? []) as Row[];
    },
  });

  useEffect(() => {
    if (prefill) {
      setEditing({ row: null, values: emptyForm(config.fields, { ...config.defaults, ...prefill }) });
      setErrors({});
      onPrefillUsed?.();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [prefill]);

  const refresh = () => {
    qc.invalidateQueries({ queryKey: key });
    if (config.affectsSite) qc.invalidateQueries({ queryKey: SITE_DATA_KEY });
  };

  const save = useMutation({
    mutationFn: async ({ row, values }: { row: Row | null; values: FormValues }) => {
      const creating = row === null;
      const payload = formToRow(config.fields, values, { creating });
      const { error } = creating
        ? await supabase!.from(config.table).insert(payload)
        : await supabase!.from(config.table).update(payload).eq(config.pk, row[config.pk] as string | number);
      if (error) throw error;
    },
    onSuccess: () => {
      toast.success("Tersimpan");
      setEditing(null);
      refresh();
    },
    onError: (e) => toast.error(dbErrorMessage(e)),
  });

  const remove = useMutation({
    mutationFn: async (row: Row) => {
      const { error } = await supabase!.from(config.table).delete().eq(config.pk, row[config.pk] as string | number);
      if (error) throw error;
    },
    onSuccess: () => {
      toast.success("Dihapus");
      refresh();
    },
    onError: (e) => toast.error(dbErrorMessage(e)),
  });

  const submit = () => {
    if (!editing) return;
    const errs = checkForm(config.fields, editing.values);
    setErrors(errs);
    if (Object.keys(errs).length) {
      toast.error("Periksa lagi isian yang ditandai merah.");
      return;
    }
    save.mutate(editing);
  };

  return (
    <section className="space-y-3">
      <div className="flex items-start justify-between gap-3">
        <div>
          <h2 className="font-body font-bold text-lg text-foreground">{config.title}</h2>
          {config.description && <p className="text-sm text-muted-foreground mt-0.5">{config.description}</p>}
        </div>
        {!editing && (
          <Button
            size="sm"
            onClick={() => {
              setEditing({ row: null, values: emptyForm(config.fields, config.defaults) });
              setErrors({});
            }}
          >
            <Plus className="w-4 h-4" /> Tambah {config.itemName}
          </Button>
        )}
      </div>

      {editing && (
        <form
          onSubmit={(e) => {
            e.preventDefault();
            submit();
          }}
          className="rounded-lg border border-gold/40 bg-card p-4 space-y-4"
        >
          <p className="font-body font-bold text-sm text-gold">
            {editing.row ? `Ubah ${config.itemName}` : `${config.itemName[0].toUpperCase()}${config.itemName.slice(1)} baru`}
          </p>
          <div className="grid sm:grid-cols-2 gap-4">
            {config.fields.map((f) => (
              <FieldInput
                key={f.key}
                field={f}
                value={editing.values[f.key]}
                error={errors[f.key]}
                disabled={save.isPending || (Boolean(editing.row) && f.createOnly)}
                onChange={(v) => setEditing((e) => (e ? { ...e, values: { ...e.values, [f.key]: v } } : e))}
              />
            ))}
          </div>
          <div className="flex gap-2 justify-end">
            <Button type="button" variant="ghost" onClick={() => setEditing(null)} disabled={save.isPending}>
              Batal
            </Button>
            <Button type="submit" disabled={save.isPending}>
              {save.isPending && <Loader2 className="w-4 h-4 animate-spin" />} Simpan
            </Button>
          </div>
        </form>
      )}

      {isLoading ? (
        <div className="flex items-center gap-2 text-sm text-muted-foreground py-6">
          <Loader2 className="w-4 h-4 animate-spin" /> Memuat…
        </div>
      ) : error ? (
        <p className="text-sm text-red-400">{dbErrorMessage(error)}</p>
      ) : rows.length === 0 ? (
        <p className="text-sm text-muted-foreground py-4">Belum ada data.</p>
      ) : (
        <ul className="divide-y divide-border rounded-lg border border-border bg-card">
          {rows.map((row) => {
            const img = config.rowImage?.(row);
            return (
              <li key={String(row[config.pk])} className="flex items-center gap-3 p-3">
                {img !== undefined && (
                  <div className="w-12 h-12 flex-shrink-0 rounded bg-[#2a2a2a] border border-border flex items-center justify-center overflow-hidden">
                    {img && <img src={img} alt="" className="max-w-full max-h-full object-contain" referrerPolicy="no-referrer" />}
                  </div>
                )}
                <div className="flex-1 min-w-0">
                  <p className="font-body text-sm text-foreground break-words line-clamp-2">{config.rowTitle(row)}</p>
                  {config.rowSubtitle && <div className="text-xs text-muted-foreground mt-0.5">{config.rowSubtitle(row)}</div>}
                </div>
                <div className="flex items-center gap-1 flex-shrink-0">
                  {config.rowActions?.(row)}
                  <Button
                    size="icon"
                    variant="ghost"
                    aria-label="Ubah"
                    onClick={() => {
                      setEditing({ row, values: rowToForm(config.fields, row) });
                      setErrors({});
                      window.scrollTo({ top: 0, behavior: "smooth" });
                    }}
                  >
                    <Pencil className="w-4 h-4" />
                  </Button>
                  <Button
                    size="icon"
                    variant="ghost"
                    aria-label="Hapus"
                    className="text-red-400 hover:text-red-300"
                    disabled={remove.isPending}
                    onClick={() => {
                      if (window.confirm(`Hapus "${config.rowTitle(row)}"? Ini tidak bisa dibatalkan.`)) remove.mutate(row);
                    }}
                  >
                    <Trash2 className="w-4 h-4" />
                  </Button>
                </div>
              </li>
            );
          })}
        </ul>
      )}
    </section>
  );
};

export default ResourceEditor;
